#!/usr/bin/env python3
"""Generate web/default_image.js from the vendor program's capture.

The mouse does not implement reads (GetFeature returns garbage or zeros), so the
configurator works on a known image: the one the vendor itself writes for its
factory configuration. It is rebuilt from tools/probe/baseline.log (shim commits)
and stored as a hex string in an ES module so the web UI can import it with no
network and no extra files.

    python3 tools/make_default_image.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from probe.parse_log import parse, memory  # noqa: E402

SIZE = 0x500
SRC = os.path.join(HERE, "probe", "baseline.log")
OUT = os.path.join(ROOT, "web", "default_image.js")

HEADER = """// Memory image the vendor program writes with its factory config.ini, rebuilt
// from tools/probe/baseline.log (generated by tools/make_default_image.py; do
// not edit by hand).
//
// This mouse does not answer reads (GetFeature returns garbage), so the
// configuration is built from this image and written whole, the same way the
// vendor does it. The bytes it does not write (0x0080-0x009F) stay at 0x00.
"""


def main():
    commits = parse(SRC)
    mem = memory(commits)
    img = bytearray(SIZE)
    for addr, value in mem.items():
        if 0 <= addr < SIZE:
            img[addr] = value
    hexs = img.hex()
    written = sorted(mem)
    print("bytes written by the vendor: %d of %#x" % (len(written), SIZE))
    print("range: %#06x..%#06x" % (written[0], written[-1]))
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(HEADER)
        fh.write('export const DEFAULT_MEM_HEX =\n  "%s";\n' % hexs)
    print("wrote", OUT, len(hexs), "hex chars")


if __name__ == "__main__":
    main()
